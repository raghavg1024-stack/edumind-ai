import {chromium} from '@playwright/test';
import fs from 'node:fs';
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:3000',{waitUntil:'networkidle'});
 await page.getByRole('heading',{name:/Welcome back/}).waitFor();
 const nav=page.getByRole('navigation',{name:'Mobile navigation'});
 if(!await nav.isVisible())throw new Error('Mobile navigation missing');
 const mobileBar=await nav.evaluate(el=>({position:getComputedStyle(el).position,bottom:el.getBoundingClientRect().bottom}));
 if(mobileBar.position!=='fixed'||Math.abs(mobileBar.bottom-844)>1)throw new Error('Mobile navigation is not fixed at the bottom');
 await page.screenshot({path:'docs/stitch-dashboard-mobile.png',fullPage:true});
 await nav.getByRole('button',{name:'Galaxy',exact:true}).click();
 await page.getByRole('heading',{name:'Knowledge Galaxy',exact:true}).waitFor();
 await page.getByRole('button',{name:'Zoom in',exact:true}).click();
 await page.getByRole('button',{name:'Reset map zoom',exact:true}).click();
 await page.screenshot({path:'docs/stitch-galaxy-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Review with AI Tutor',exact:true}).click();
 await page.getByText('Here are the relevant passages',{exact:false}).waitFor();
 await page.screenshot({path:'docs/stitch-tutor-mobile.png',fullPage:true});
 await nav.getByRole('button',{name:'Practice',exact:true}).click();
 await page.getByRole('button',{name:'Generate quiz',exact:true}).click();
 const fields=page.locator('.quiz-question');
 for(let i=0;i<await fields.count();i++)await fields.nth(i).locator('input[type=radio]').first().check();
 await page.getByRole('button',{name:'Check answers',exact:true}).click();
 await page.getByText('Your score and study plan are updated.',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Revisit source',exact:true}).first().click();
 await page.getByRole('dialog').waitFor();
 await page.getByRole('button',{name:'Close dialog',exact:true}).click();
 await nav.getByRole('button',{name:'Hub',exact:true}).click();
 await page.getByRole('button',{name:'Smart Classroom',exact:true}).click();
 await page.getByRole('heading',{name:'Your lectures, brought to life.',exact:true}).waitFor();
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 if(overflow)throw new Error('Mobile layout overflows');
 await page.setViewportSize({width:1440,height:1000});
 if(await nav.isVisible())throw new Error('Bottom navigation should be hidden on laptop');
 if(!await page.locator('.sidebar').isVisible())throw new Error('Laptop sidebar is missing');
 await page.getByRole('navigation',{name:'Main navigation',exact:true}).getByRole('button',{name:'Overview',exact:true}).click();
 await page.screenshot({path:'docs/stitch-dashboard-desktop.png',fullPage:true});
 if(errors.length)throw new Error(errors.join('\n'));
 fs.writeFileSync('docs/stitch-verification.json',JSON.stringify({tested_at:new Date().toISOString(),status:'passed',checks:['mobile dashboard','galaxy navigation and zoom','source-grounded tutor','quiz grading and revision citation','classroom navigation','mobile overflow','desktop dashboard'],page_errors:errors},null,2));
 await browser.close();console.log('Stitch UI verification passed');
})().catch(e=>{console.error(e);process.exit(1)});

